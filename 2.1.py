
# Плоское движение планеты вокруг звезды.
# Единицы СГС: см, г, с.

import numpy as np
import matplotlib.pyplot as plt


def planet2D(x0, y0, vx0, vy0, Mc, m, dt, N):
    # Функция считает траекторию планеты.
    # Выход:
    #   r - массив 2 x N, координаты планеты
    #   t - массив из N моментов времени
    G = 6.67430e-8   # гравитационная постоянная в СГС
    mu = G * Mc             
    
    
    r = np.zeros((2, N)) # r - две строки: r[0] это все X, r[1] это все Y.
    t = np.zeros(N) # t - просто времена: 0, dt, 2*dt...

    # Текущие координаты и скорости
    x = x0
    y = y0
    vx = vx0
    vy = vy0

    # Ускорение в начальной точке
    # rr - расстояние до звезды (звезда в начале координат).
    # По закону тяготения a = -mu * r / r^3.
    rr = np.sqrt(x*x + y*y)
    ax = -mu * x / (rr*rr*rr)
    ay = -mu * y / (rr*rr*rr)

    # Половинный "пинок" для старта схемы с перешагом
    # Нужен потому, что в схеме с перешагом скорости живут
    # на полушагах (n±1/2), а координаты - на целых шагах.
    # Первый полный пинок мы делаем в цикле, поэтому чтобы
    # стартовать, надо заранее сдвинуть скорость на полшага.
    vx = vx + 0.5 * dt * ax
    vy = vy + 0.5 * dt * ay

    # Первая точка
    r[0, 0] = x
    r[1, 0] = y
    t[0] = 0.0

    # Основной цикл
    for k in range(1, N):

        # 1. Дрейф, сдвигаем координаты
        x = x + dt * vx
        y = y + dt * vy

        # 2. Новое ускорение
        rr = np.sqrt(x*x + y*y)
        ax = -mu * x / (rr*rr*rr)
        ay = -mu * y / (rr*rr*rr)

        # 3. Пинок - меняем скорость
        vx = vx + dt * ax
        vy = vy + dt * ay

        # Запоминаем точку
        r[0, k] = x
        r[1, k] = y
        t[k] = k * dt
        
    return r, t


