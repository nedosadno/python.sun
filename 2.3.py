import numpy as np                                    # импорт numpy для массивов и математики
import matplotlib.pyplot as plt                       # импорт pyplot для графиков


# Функции силы (ускорения) для центральных полей.
#
# Центральное поле - это поле, где сила направлена строго вдоль
# радиус-вектора, проведённого из центра. Записывается как
# F = f(r)*r_hat, где r_hat = r/|r| - единичный вектор вдоль r.
#
# Все рассматриваемые силы направлены к центру (притяжение),
# поэтому f(r) < 0. Это гравитационные силы и их аналоги.
# Масса точки равна 1, поэтому ускорение a = F.

def force_const(r, alpha=1.0):
    # F = -alpha*r_hat - постоянная по модулю сила к центру.
    # Соответствует потенциалу U = alpha*r.
    # Из U = alpha*r: F = -dU/dr = -alpha, то есть const.
    return -alpha * r / np.linalg.norm(r)             # -alpha * r/|r| = -alpha * r_hat


def force_inv_sq(r, alpha=1.0):
    # F = -alpha/r^2 * r_hat - ньютоновское поле (гравитация, Кулон).
    return -alpha * r / np.linalg.norm(r)**3          # -alpha * r/|r|^3 = -alpha/|r|^2 * r_hat


def force_inv_n(r, alpha=1.0, n=3):
    # F = -alpha/r^n * r_hat - общая степенная сила.
    return -alpha * r / np.linalg.norm(r)**(n + 1)    # -alpha * r/|r|^(n+1) = -alpha/|r|^n * r_hat


def movement2D(x0, y0, vx0, vy0, dt, N, force):
    # Движение точки единичной массы в центральном поле.
    # Вид силы передаётся параметром - функцией force(r).
    # Параметры:
    #     x0, y0   - начальные координаты
    #     vx0, vy0 - начальные скорости
    #     dt       - шаг по времени
    #     N        - число шагов
    #     force    - функция силы: force(r) возвращает ускорение
    #
    # Возврат:
    #     R - траектория (N+1, 2)
    #     t - моменты времени (N+1,)
    #     L - удельный момент импульса L = x*vy - y*vx (N+1,)
    r = np.array([x0, y0], dtype=float)               # массив (2,), начальная позиция
    v = np.array([vx0, vy0], dtype=float)             # массив (2,), начальная скорость

    R = np.zeros((N + 1, 2))                          # массив (N+1, 2), траектория R[k] = (x_k, y_k)
    L = np.zeros(N + 1)                               # массив (N+1,), удельный момент импульса
    t = np.arange(N + 1) * dt                         # массив (N+1,), моменты времени t_k = k*dt

    R[0] = r                                          # записываем начальную позицию
    L[0] = r[0] * v[1] - r[1] * v[0]                  # L[0] = x_0*vy_0 - y_0*vx_0 (z-компонента [r x v])

    for k in range(N):                                # цикл по шагам, k = 0, 1, ..., N-1
        # полшага по скорости со старой силой.
        # Полшага - потому что полный сдвиг делается двумя порциями
        v_half = v + 0.5 * force(r) * dt              # массив (2,), скорость через полшага

        # полный шаг координаты со средней скоростью v_half
        r_new = r + v_half * dt                       # массив (2,), новая позиция

        # полшага по скорости с новой силой.
        # Порядок  симметричен: половина, целый, половина.
        # Силы вычисляются в старой и новой точках 
        v_new = v_half + 0.5 * force(r_new) * dt      # массив (2,), новая скорость

        r, v = r_new, v_new                           # обновляем состояние
        R[k + 1] = r                                  # записываем новую позицию
        L[k + 1] = r[0] * v[1] - r[1] * v[0]          # L[k+1] = x*vy - y*vx в новой точке

    return R, t, L                                    # возвращаем траекторию, времена, момент



# Секториальная скорость - это dS/dt = 0.5*|[r x v]| = L/(2m).
# Она сохраняется в ЛЮБОМ центральном поле, потому что момент силы
# относительно центра равен нулю: [r x F] = [r x f(r)*r_hat] = 0.

# По заданию: U = alpha*r, F ~ 1/r^2, F ~ 1/r^n, F = const.
#  U = alpha*r эквивалентно F = const, потому что
# F = -dU/dr = -alpha. Первый и четвёртый случаи дают одно поле.

alpha = 2.0                                           # скаляр, коэффициент силы
r0    = 1.0                                           # скаляр, начальное расстояние от центра
dt    = 0.001                                          # скаляр, шаг по времени
N     = 10000                                          # число шагов

cases = [                                             # список кортежей (название, функция силы, начальная скорость)
    ("Потенциал U = alpha*r ",
        lambda r: force_const(r, alpha),         0.9),
    ("Сила F = -alpha/r^2",
        lambda r: force_inv_sq(r, alpha),        0.8),
    ("Сила F = -alpha/r^3 ",
        lambda r: force_inv_n(r, alpha, n=3),    1.4),
    ("Сила F = const  (совпадает с U = alpha*r)",
        lambda r: force_const(r, alpha),         0.9),
]

fig, axes = plt.subplots(2, 4, figsize=(16, 7))       # окно 2 строки x 4 столбца

print(f"{'Поле':<40} {'max|dL|/L0':<15}")             # шапка таблицы результатов
print("-" * 58)                                        # разделитель

for i, (name, force, v0) in enumerate(cases):          # перебор четырёх полей
    R, t, L = movement2D(r0, 0.0, 0.0, v0, dt, N, force)  # прогон: траектория, времена, момент

    # Верхний ряд: траектория
    axes[0, i].plot(R[:, 0], R[:, 1], lw=0.8)          # R[:,0] - все x, R[:,1] - все y
    axes[0, i].plot(0, 0, 'ko', ms=5)                  # чёрная точка - центр сил
    axes[0, i].plot(R[0, 0], R[0, 1], 'go', ms=5)      # зелёная точка - старт
    axes[0, i].set_aspect('equal')                     # равный масштаб по осям
    axes[0, i].set_title(name, fontsize=9)             # заголовок - название поля
    axes[0, i].grid(alpha=0.3)                         # сетка

    # Нижний ряд: относительное отклонение момента импульса.
    # В центральном поле он сохраняется, поэтому кривая должна
    # осциллировать около нуля, но не расти со временем.
    L_rel = np.abs(L - L[0]) / abs(L[0])               # массив (N+1,), |L(t) - L(0)| / L(0)
    axes[1, i].semilogy(t, L_rel + 1e-20)              # лог-масштаб по y, +1e-20 чтобы не брать log(0)
    axes[1, i].set_xlabel('t')                         # подпись оси x
    axes[1, i].set_ylabel('|dL| / L0')                 # подпись оси y
    axes[1, i].set_title(f'max = {np.max(L_rel):.2e}', fontsize=9)  # максимум ошибки в заголовке
    axes[1, i].grid(alpha=0.3, which='both')           # сетка по мелким и крупным делениям

    print(f"{name:<40} {np.max(L_rel):<15.3e}")        # печатаем строку таблицы: поле и его ошибка

plt.tight_layout()                                     # подгоняем отступы
plt.show()                                             # показываем все графики