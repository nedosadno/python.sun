import numpy as np                      # массивы и математика
import matplotlib.pyplot as plt         # графики
from matplotlib.widgets import Slider   # интерактивные ползунки

# Фиксируем зерно генератора случайных чисел.
# Компьютер умеет генерировать только псевдослучайные числа — детерминированную последовательность, которая "выглядит случайной".
# Зерно (seed) задаёт её начальное состояние, поэтому при каждом запуске
# числа будут одинаковыми — результат воспроизводим.
np.random.seed(0)

N     = 5000      # число частиц
dh    = 1.0       # максимальный шаг одной частицы за один шаг по времени
n_max = 500       # максимальное число шагов по времени


# Нам нужно N независимых траекторий по n_max шагов.
# Каждый отдельный шаг — независимая случайная величина, равномерная
# на отрезке [-dh, dh]:
#     p(xi) = 1/(2*dh)  при xi in [-dh, dh].
#
# Удобно сразу сгенерировать всю матрицу шагов формы (n_max, N):
#     steps[k, i] — смещение i-й частицы на (k+1)-м шаге по времени
steps = np.random.normal(loc = 0.0 ,scale = dh/(3**(0.5)), size=(n_max, N))

# Координата частицы после n шагов — сумма первых n её смещений.
# Накопительная сумма np.cumsum(..., axis=0)
# После вызова:
#     traj[k-1, i] = сумма steps[0..k-1, i]
#                  = координата i-й частицы после k шагов.
traj = np.cumsum(steps, axis=0)


def sigma_theor(n): 
    return dh * np.sqrt(n / 3.0)

# Строим 6 подграфиков. На каждой панели — гистограмма координат
# всех N частиц в выбранный момент времени n, плюс гауссовы кривые.
fig1, axes = plt.subplots(2, 3, figsize=(14, 8))

times = [1, 5, 20, 50, 200, 500]   # моменты времени (число шагов)
bins  = 50                          # число бинов гистограммы (общее для всех)

for ax_, n in zip(axes.ravel(), times):

    # Берём строку матрицы traj, соответствующую состоянию после n шагов:
    # это вектор длины N — координаты всех частиц в этот момент.
    x = traj[n - 1]

    # Гистограмма распределения координат.
    # density=True нормирует её на 1, чтобы она была оценкой плотности
    # вероятности, и её можно было накладывать на гауссовы кривые.
    ax_.hist(x, bins=bins, density=True, alpha=0.55, color='C0',
             label='гистограмма')

    # Сетка по x для гладкой отрисовки гауссовых кривых.
    xs = np.linspace(x.min(), x.max(), 400)

    # Экспериментальные параметры распределения по текущей выборке:
    #   mu_exp  = (1/N) * sum(x_i)                       — среднее
    #   sig_exp = sqrt( (1/N) * sum((x_i - mu_exp)^2) )  — СКО
    # ddof=0 означает деление на N (а не на N-1).
    mu_exp  = x.mean()
    sig_exp = x.std(ddof=0)

    # Теоретическое СКО после n шагов dh*sqrt(n/3).
    sig_th  = sigma_theor(n)

    # Плотность нормального распределения:
    #     p(x) = 1/(sqrt(2*pi)*sigma) * exp( -(x-mu)^2 / (2*sigma^2) ).
    # Экспериментальный Гаусс — с параметрами (mu_exp, sig_exp).
    g_exp = np.exp(-(xs - mu_exp)**2 / (2 * sig_exp**2)) \
            / (np.sqrt(2 * np.pi) * sig_exp)
    # Теоретический Гаусс — с параметрами (0, sig_th).
    g_th = np.exp(-xs**2 / (2 * sig_th**2)) \
           / (np.sqrt(2 * np.pi) * sig_th)

    ax_.plot(xs, g_exp, 'C1',  lw=2, label=f'Гаусс эксп: sigm={sig_exp:.3f}')
    ax_.plot(xs, g_th,  'C3--', lw=2, label=f'Гаусс теор: sigm={sig_th:.3f}')

    rel = abs(sig_exp - sig_th) / sig_th

    ax_.set_title(f'n = {n}   |Δsigm|/sigm = {rel*100:.2f}%')
    ax_.set_xlabel('x')
    ax_.set_ylabel('p(x)')
    ax_.grid(alpha=0.3)
    ax_.legend(fontsize=8)

fig1.suptitle(f'Эволюция распределения координат (N = {N}, dh = {dh})', fontsize=12)
plt.tight_layout()
plt.show()


# гистограмма с ползунками
#   создаём фигуру и главные оси ax2, где будем всё рисовать;
#   добавляем доп оси-прямоугольники, на которых разместятся
#     ползунки Slider;
#   пишем функцию update(), которая читает текущие значения ползунков
#     и заново рисует сцену;
#   подписываемся на событие изменения: s.on_changed(update).
# Теперь matplotlib сам вызовет update() при каждом сдвиге ползунка.

fig2, ax2 = plt.subplots(figsize=(10, 6))
# bottom=0.25 освобождает 25% высоты фигуры снизу под ползунки.
plt.subplots_adjust(bottom=0.25)

ax_step = plt.axes([0.15, 0.12, 0.7, 0.03])   # верхний ползунок
ax_bins = plt.axes([0.15, 0.06, 0.7, 0.03])   # нижний ползунок

# Slider(ось, подпись, минимум, максимум, начальное значение, шаг).
# valstep=1 — значение меняется только целыми числами.
s_step = Slider(ax_step, 'шаг',   1, n_max, valinit=100, valstep=1)
s_bins = Slider(ax_bins, 'бинов', 5, 200,   valinit=50,  valstep=1)


def update(_=None):
    # Перерисовать сцену при изменении любого ползунка.
    # Аргумент _ нужен, потому что matplotlib передаёт сюда текущее
    # значение слайдера; нам оно не нужно — читаем его из s_step.val.

    n    = int(s_step.val)   # текущее число шагов по ползунку
    bins = int(s_bins.val)   # текущее число бинов гистограммы

    # traj уже полностью посчитана — просто берём готовую строку.
    x = traj[n - 1]

    #  стереть старую картинку с ax2.
    # Без этого при каждом обновлении новая гистограмма и новые кривые
    # рисовались бы поверх предыдущих, и ось "зарастала" бы графикой.
    ax2.clear()

    # Гистограмма с новым числом бинов.
    ax2.hist(x, bins=bins, density=True, alpha=0.55, color='C0',
             label='гистограмма')

    # Сетка по x для гауссовых кривых.
    xs = np.linspace(x.min(), x.max(), 400)

    # Экспериментальные и теоретические параметры.
    mu_exp  = x.mean()
    sig_exp = x.std(ddof=0)
    sig_th  = sigma_theor(n)

    # Плотности нормального распределения.
    g_exp = np.exp(-(xs - mu_exp)**2 / (2 * sig_exp**2)) \
            / (np.sqrt(2 * np.pi) * sig_exp)
    g_th = np.exp(-xs**2 / (2 * sig_th**2)) \
           / (np.sqrt(2 * np.pi) * sig_th)

    ax2.plot(xs, g_exp, 'C1',  lw=2,
             label=f'Гаусс эксп: μ={mu_exp:.3f}, sigm={sig_exp:.3f}')
    ax2.plot(xs, g_th,  'C3--', lw=2,
             label=f'Гаусс теор: μ=0,      sigm={sig_th:.3f}')

    rel = abs(sig_exp - sig_th) / sig_th
    ax2.set_title(f'N = {N}, шагов n = {n}, бинов = {bins}\n'
                  f'|sigm_эксп − sigm_теор| / sigm_теор = {rel*100:.2f}%')
    ax2.set_xlabel('x')
    ax2.set_ylabel('p(x)')
    ax2.grid(alpha=0.3)
    ax2.legend(loc='upper right', fontsize=9)

    # Просьба к холсту перерисовать себя. draw_idle планирует
    # перерисовку на ближайшем цикле событий — быстрее, чем draw().
    fig2.canvas.draw_idle()


# Подписка на события: при сдвиге ползунков вызывать update().
s_step.on_changed(update)
s_bins.on_changed(update)

# Первый вызов вручную — чтобы окно сразу открылось с начальным состоянием.
update()
plt.show()


# сходимостЬ sigm_эксп К sigm_теор  и проверка 1% критерия
# Ключевая мысль: sigma_theor(n) — точная формула, поэтому "истинной"
# зависимости ошибки от n нет. Реально ошибка |sigm_эксп − sigm_теор| / sigm_теор
# определяется статистическим шумом выборки из N частиц.
# Для нормальной выборки стандартная ошибка оценки sigm:
#     δsigm/sigm = 1 / sqrt(2N).
# Отсюда критерий 1%:  1/sqrt(2N) < 0.01  =>  N > 5000.
# То есть достижимость 1% определяется числом частиц

def rel_err_curve(N_, n_max_, n_real=8):
    # Средняя по нескольким реализациям относительная ошибка sigm_эксп
    # как функция числа шагов n = 1..n_max_.
    # Усреднение по n_real реализациям убирает случайный разброс
    # и оставляет систематическую картину.

    n_arr = np.arange(1, n_max_ + 1)
    err   = np.zeros(n_max_)
    for _ in range(n_real):
        # Своя случайная матрица шагов формы (n_max_, N_).
        s  = np.random.uniform(-dh, dh, size=(n_max_, N_))
        # traj_re — координаты всех частиц по шагам.
        tr = np.cumsum(s, axis=0)
        # sigm выборки на каждом шаге (std вдоль оси частиц).
        sg = tr.std(axis=1, ddof=0)
        # Накопление относительной ошибки.
        err += np.abs(sg - sigma_theor(n_arr)) / sigma_theor(n_arr)
    return err / n_real


fig3, ax3 = plt.subplots(figsize=(9, 6))

# Несколько значений N — чтобы увидеть, как ошибка зависит от числа частиц.
Ns_demo = [50, 200, 1000, 5000, 20000]

for N_ in Ns_demo:
    err = rel_err_curve(N_, n_max, n_real=8)
    # log-log, потому что ошибка убывает как 1/sqrt(N) — на двойном
    # лог-масштабе это наклонная прямая с наклоном −1/2.
    ax3.loglog(np.arange(1, n_max + 1), err, lw=1.4, label=f'N = {N_}')

# Горизонтальная линия-ориентир: порог 1%.
ax3.axhline(0.01, color='k', ls='--', lw=1, label='порог 1%')
ax3.set_xlabel('n — число шагов')
ax3.set_ylabel(r'$\langle\,|\sigma_{эксп} - \sigma_{теор}|/\sigma_{теор}\,\rangle$')
ax3.set_title('Сходимость экспериментального СКО к теоретическому')
ax3.grid(alpha=0.3, which='both')
ax3.legend()
plt.tight_layout()
plt.show()

# Для каждого N находим первое n, при котором ошибка < 1%.
# Если такого n нет — печатаем, что критерий не достигается.
print("Проверка 1%-критерия (усреднено по реализациям):")
for N_ in Ns_demo:
    err   = rel_err_curve(N_, n_max, n_real=8)
    below = np.where(err < 0.01)[0]
    if len(below) > 0:
        print(f"  N = {N_:>6}: первое n, где ошибка < 1%  ->  n = {below[0] + 1}")
    else:
        print(f"  N = {N_:>6}: критерий 1% не достигается до n = {n_max}")